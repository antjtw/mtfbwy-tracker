/*
 * Rebuilds every tracker character as a half-built Hero (see lib/hero/legacy.ts) and writes
 * supabase/legacy-heroes.sql. Safe to re-run: heroes that already exist are left alone.
 * Prints what couldn't be matched to the rules data.
 */
import { writeFileSync } from "node:fs";
import { heroFromCharacter } from "../lib/hero/legacy";
import { computeHero } from "../lib/hero/engine";
import { SEED_CHARACTERS } from "../lib/seed";

const q = (v: string) => `'${v.replace(/'/g, "''")}'`;
const rows: string[] = [];
const report: string[] = [];
for (const c of SEED_CHARACTERS) {
  const { hero, unmapped } = heroFromCharacter(c);
  rows.push(`(${q(c.id)}, ${q(c.player_id)}, ${q(hero.rulesVersion)}, ${q(JSON.stringify(hero))}::jsonb)`);
  const open = computeHero(hero).issues.length;
  report.push(`${c.name.padEnd(28)} level ${String(hero.levelLog.length + 1).padEnd(2)} open items ${String(open).padEnd(3)} ${unmapped.length ? "unmapped: " + unmapped.join("; ") : ""}`);
}
writeFileSync(
  new URL("../supabase/legacy-heroes.sql", import.meta.url),
  `-- Generated by \`npm run heroes:legacy\`. Rebuilds each existing tracker character as a half-built Hero.
-- Safe to re-run: a Hero that already exists (built or completed) is never overwritten.
-- Needs supabase/migrations/2026-11-15-add-heroes.sql first.
insert into heroes (id, player_id, rules_version, data) values
  ${rows.join(",\n  ")}
on conflict (id) do nothing;
`,
);
console.log(report.join("\n"));
console.log(`\n${SEED_CHARACTERS.length} Heroes written to supabase/legacy-heroes.sql`);
